#!/usr/bin/env bash
# =============================================================================
# setup-hotspot.sh — turn the Realtek USB WiFi adapter into a WiFi hotspot
#                    that shares the wired uplink (enp7s0).
#
# Idempotent: safe to re-run any time. The wlan interface name does NOT need
# to be pinned — it is auto-detected by driver (rtw89) on every run and at
# every boot, and the network config matches the adapter by MAC address.
#
# Usage:   sudo ./setup-hotspot.sh          (or edit the VARS below first)
#          SSID=foo PASSWORD=bar1234 sudo -E ./setup-hotspot.sh
#
# Later changes: edit the VARS and re-run, everything is regenerated.
# =============================================================================
set -euo pipefail

if [ "$EUID" -ne 0 ]; then
    echo "Error: This script must be run as root."
    exit 1
fi

# ======================== VARS — EDIT THESE ================================
SSID="${SSID:-${HOSTNAME}hotspot}"     # WiFi network name        (1-32 chars)
PASSWORD="${PASSWORD:-hotspot1234}"    # WPA2 password            (8-63 chars)
HW_MODE="${HW_MODE:-a}"                # g = 2.4 GHz, a = 5 GHz
CHANNEL="${CHANNEL:-44}"               # g: 1/6/11   a: 36/40/44/48
COUNTRY="${COUNTRY:-GB}"               # regulatory domain
UPSTREAM="${UPSTREAM:-enp7s0}"         # interface whose internet we share
DRIVER_MATCH="${DRIVER_MATCH:-rtw89}"  # sysfs driver prefix used to find the WiFi adapter
AP_IP="${AP_IP:-10.42.0.1}"            # hotspot gateway IP
AP_CIDR="${AP_CIDR:-24}"
NETMASK="${NETMASK:-255.255.255.0}"
DHCP_START="${DHCP_START:-10.42.0.10}"
DHCP_END="${DHCP_END:-10.42.0.250}"
DHCP_LEASE="${DHCP_LEASE:-12h}"
DNS_UPSTREAM="${DNS_UPSTREAM:-9.9.9.9}" # Quad9 secure DNS (primary)
DNS_UPSTREAM2="${DNS_UPSTREAM2:-149.112.112.112}" # Quad9 secure DNS (secondary)
DISABLE_IWD="${DISABLE_IWD:-yes}"       # iwd fights hostapd for the adapter
# ============================================================================

log()  { printf '\e[1;32m==>\e[0m %s\n' "$*"; }
warn() { printf '\e[1;33mwarn:\e[0m %s\n' "$*" >&2; }
die()  { printf '\e[1;31merror:\e[0m %s\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || exec sudo -- "$0" "$@"

# --- validate vars ----------------------------------------------------------
[[ ${#SSID}     -ge 1 && ${#SSID}     -le 32 ]] || die "SSID must be 1-32 chars"
[[ ${#PASSWORD} -ge 8 && ${#PASSWORD} -le 63 ]] || die "PASSWORD must be 8-63 chars"
[[ "$HW_MODE" == g || "$HW_MODE" == a ]]        || die "HW_MODE must be 'g' or 'a'"
if [[ "$HW_MODE" == g && ! "$CHANNEL" =~ ^(1|6|11)$ ]]; then
  warn "channel $CHANNEL is unusual for 2.4 GHz; 1, 6 or 11 are recommended"
fi

# --- packages ---------------------------------------------------------------
log "Installing packages (hostapd, dnsmasq, wireless-regdb)..."
pacman -S --needed --noconfirm hostapd dnsmasq wireless-regdb
log "If wireless-regdb was just installed, a restart is required"

# --- iwd would steal the interface from hostapd ------------------------------
# Mask (not just disable): iwd.service is Type=dbus, so any D-Bus client can
# re-activate it on demand even when "disabled".
if [[ "$DISABLE_IWD" == yes ]]; then
  log "Disabling + masking iwd..."
  systemctl disable --now iwd.service 2>/dev/null || true
  systemctl mask iwd.service 2>/dev/null || true
  systemctl stop 'wpa_supplicant@'* 2>/dev/null || true
fi

# --- stop USB autosuspend resetting the dongle -------------------------------
log "Disabling USB autosuspend for the Realtek dongle..."
cat > /etc/udev/rules.d/50-rtw89-no-autosuspend.rules <<'EOF'
# Keep the Realtek WiFi/BT dongle powered (autosuspend causes resets/re-enumerations).
ACTION=="add", SUBSYSTEM=="usb", ATTR{idVendor}=="0bda", TEST=="power/control", ATTR{power/control}="on"
EOF
udevadm control --reload 2>/dev/null || true
udevadm trigger --subsystem-match=usb 2>/dev/null || true

# --- persist the vars for the boot-time detect script ------------------------
log "Writing /etc/default/hotspot..."
cat > /etc/default/hotspot <<EOF
# Generated by setup-hotspot.sh — edit these and re-run the script to apply.
SSID="$SSID"
PASSWORD="$PASSWORD"
HW_MODE="$HW_MODE"
CHANNEL="$CHANNEL"
COUNTRY="$COUNTRY"
UPSTREAM="$UPSTREAM"
DRIVER_MATCH="$DRIVER_MATCH"
AP_IP="$AP_IP"
AP_CIDR="$AP_CIDR"
NETMASK="$NETMASK"
DHCP_START="$DHCP_START"
DHCP_END="$DHCP_END"
DHCP_LEASE="$DHCP_LEASE"
DNS_UPSTREAM="$DNS_UPSTREAM"
DNS_UPSTREAM2="$DNS_UPSTREAM2"
EOF
chmod 600 /etc/default/hotspot

# --- boot-time generator: detects the (renamed) adapter, writes configs ------
log "Writing /usr/local/sbin/hotspot-detect..."
cat > /usr/local/sbin/hotspot-detect <<'SCRIPT'
#!/usr/bin/env bash
# Regenerates hostapd/dnsmasq/networkd config for the current wlan interface
# name. Run at boot by hotspot-setup.service; safe to run manually.
set -euo pipefail
. /etc/default/hotspot

rfkill unblock wifi 2>/dev/null || true

# The adapter's interface name drifts (wlan0, wlan5, wlan6, ...). Find it by
# driver, waiting up to 15 s for USB enumeration at boot.
IFACE=""
for _ in $(seq 1 30); do
  for n in /sys/class/net/*; do
    [[ -e "$n/phy80211" ]] || continue
    drv=$(basename "$(readlink -f "$n/phy80211/device/driver" 2>/dev/null || true)")
    if [[ "$drv" == "$DRIVER_MATCH"* ]]; then IFACE="${n##*/}"; break 2; fi
  done
  sleep 0.5
done
[[ -n "$IFACE" ]] || { echo "hotspot-detect: no adapter matching '$DRIVER_MATCH'" >&2; exit 1; }
echo "$IFACE" > /run/hotspot-iface

# Regulatory domain: required for 5 GHz AP mode. Under the default "world"
# domain (00) channels 36-48 are flagged NO-IR and hostapd refuses to start.
iw reg set "$COUNTRY" 2>/dev/null || true

# Verify the configured channel can actually run an AP; if not (e.g. a 5 GHz
# channel blocked by the regulatory domain) fall back to 2.4 GHz channel 6.
PHY=$(iw dev "$IFACE" info 2>/dev/null | awk '/wiphy/{print $2}')
if [[ -n "$PHY" ]]; then
  if [[ "$HW_MODE" == g ]]; then
    FREQ=$(( CHANNEL == 14 ? 2484 : 2407 + CHANNEL * 5 ))
  else
    FREQ=$((5000 + CHANNEL * 5))
  fi
  ENTRY=$(iw phy "phy$PHY" info 2>/dev/null \
            | grep -E "^[[:space:]]*\* ${FREQ}\.[0-9]+ MHz \[${CHANNEL}\]" | head -1)
  if [[ -z "$ENTRY" || "$ENTRY" == *"no IR"* ]]; then
    echo "hotspot-detect: channel $CHANNEL ($HW_MODE) is not usable for AP mode; falling back to 2.4 GHz channel 6" >&2
    HW_MODE=g
    CHANNEL=6
  fi
fi

# hostapd defaults to 20 MHz. On supported 5 GHz channels, enable 80 MHz VHT.
# Channels 36/40/44/48 share the 80 MHz block centred on channel 42.
BAND_OPTS=""
if [[ "$HW_MODE" == a ]]; then
  case "$CHANNEL" in
    36|44) HT40="+" ;;
    40|48) HT40="-" ;;
    *) HT40="" ;;
  esac

  if [[ -n "$HT40" ]]; then
    BAND_OPTS="ht_capab=[HT40$HT40]
ieee80211ac=1
vht_oper_chwidth=1
vht_oper_centr_freq_seg0_idx=42"
  fi
fi

cat > /etc/hostapd/hostapd.conf <<EOF
# Generated by setup-hotspot.sh — do not edit (rerun the installer instead).
interface=$IFACE
driver=nl80211
ssid=$SSID
country_code=$COUNTRY
ieee80211d=1
hw_mode=$HW_MODE
channel=$CHANNEL
ieee80211n=1
$BAND_OPTS
wmm_enabled=1
auth_algs=1
ignore_broadcast_ssid=0
wpa=2
wpa_passphrase=$PASSWORD
wpa_key_mgmt=WPA-PSK
rsn_pairwise=CCMP
EOF
chmod 600 /etc/hostapd/hostapd.conf

mkdir -p /etc/dnsmasq.d
cat > /etc/dnsmasq.d/hotspot.conf <<EOF
# Generated by setup-hotspot.sh — do not edit (rerun the installer instead).
interface=$IFACE
bind-dynamic
dhcp-range=$DHCP_START,$DHCP_END,$NETMASK,$DHCP_LEASE
dhcp-option=option:router,$AP_IP
dhcp-option=option:dns-server,$AP_IP
server=$DNS_UPSTREAM
server=$DNS_UPSTREAM2
no-resolv
domain-needed
bogus-priv
EOF

# Match by MAC, not by name — survives the periodic wlanN renames.
MAC=$(cat "/sys/class/net/$IFACE/address")
cat > /etc/systemd/network/10-wlan-hotspot.network <<EOF
# Generated by setup-hotspot.sh — matches the hotspot adapter by MAC address.
[Match]
MACAddress=$MAC

[Network]
Address=$AP_IP/$AP_CIDR
ConfigureWithoutCarrier=yes
IPv6AcceptRA=no
EOF

networkctl reload 2>/dev/null || true
networkctl reconfigure "$IFACE" 2>/dev/null || true
SCRIPT
chmod 755 /usr/local/sbin/hotspot-detect

# --- hostapd must know where its config lives (Arch keeps it in conf.d) -----
CONF=/etc/conf.d/hostapd
if [[ -f "$CONF" ]] && grep -q '^DAEMON_CONF=' "$CONF"; then
  sed -i 's|^DAEMON_CONF=.*|DAEMON_CONF="/etc/hostapd/hostapd.conf"|' "$CONF"
else
  echo 'DAEMON_CONF="/etc/hostapd/hostapd.conf"' >> "$CONF"
fi

# --- make dnsmasq read /etc/dnsmasq.d/ ---------------------------------------
grep -qs '^conf-dir=/etc/dnsmasq.d' /etc/dnsmasq.conf \
  || echo 'conf-dir=/etc/dnsmasq.d/,*.conf' >> /etc/dnsmasq.conf

# --- systemd: run the detector before hostapd/dnsmasq every boot -------------
log "Installing systemd units..."
mkdir -p /etc/systemd/system/hostapd.service.d /etc/systemd/system/dnsmasq.service.d
cat > /etc/systemd/system/hotspot-setup.service <<'EOF'
[Unit]
Description=Prepare WiFi hotspot (detect adapter, generate configs)
Before=hostapd.service dnsmasq.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/local/sbin/hotspot-detect

[Install]
WantedBy=multi-user.target
EOF
cat > /etc/systemd/system/hostapd.service.d/hotspot.conf <<'EOF'
[Unit]
Requires=hotspot-setup.service
After=hotspot-setup.service

[Service]
Restart=on-failure
RestartSec=5
EOF
cp /etc/systemd/system/hostapd.service.d/hotspot.conf \
   /etc/systemd/system/dnsmasq.service.d/hotspot.conf

# --- self-heal when the dongle re-enumerates and reappears as a new wlanN ----
cat > /etc/systemd/system/hotspot-apply.service <<'EOF'
[Unit]
Description=Apply WiFi hotspot config to a (re)appearing wireless interface

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/hotspot-detect
ExecStart=/usr/bin/systemctl restart hostapd.service dnsmasq.service
EOF
cat > /etc/udev/rules.d/90-wlan-hotspot.rules <<'EOF'
# The Realtek dongle re-enumerates (USB "zero-CD" mode switch) and returns as a
# new wlanN. Regenerate configs + restart the daemons whenever a wlan appears.
ACTION=="add", SUBSYSTEM=="net", KERNEL=="wlan*", TAG+="systemd", ENV{SYSTEMD_WANTS}="hotspot-apply.service"
EOF
udevadm control --reload 2>/dev/null || true

# --- IP forwarding -----------------------------------------------------------
log "Enabling IP forwarding..."
echo 'net.ipv4.ip_forward=1' > /etc/sysctl.d/90-hotspot-forward.conf
sysctl -q -w net.ipv4.ip_forward=1

# --- NAT rules (wlanN wildcard, so renames are irrelevant) -------------------
log "Writing iptables rules..."
IPT=/etc/iptables/iptables.rules
if [[ -s "$IPT" ]] && ! grep -q 'MASQUERADE' "$IPT"; then
  cp -a "$IPT" "$IPT.bak.$(date +%Y%m%d%H%M%S)"
  warn "existing $IPT backed up to $IPT.bak.*"
fi
cat > "$IPT" <<EOF
# Generated by setup-hotspot.sh — hotspot NAT for $UPSTREAM
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
-A FORWARD -i wlan+ -o $UPSTREAM -j ACCEPT
-A FORWARD -i $UPSTREAM -o wlan+ -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
COMMIT
*nat
:PREROUTING ACCEPT [0:0]
:INPUT ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
-A POSTROUTING -o $UPSTREAM -j MASQUERADE
COMMIT
EOF
systemctl enable iptables.service
# Apply now without flushing (docker is running and owns other chains).
iptables -t nat -C POSTROUTING -o "$UPSTREAM" -j MASQUERADE 2>/dev/null \
  || iptables -t nat -A POSTROUTING -o "$UPSTREAM" -j MASQUERADE
iptables -C FORWARD -i wlan+ -o "$UPSTREAM" -j ACCEPT 2>/dev/null \
  || iptables -A FORWARD -i wlan+ -o "$UPSTREAM" -j ACCEPT
iptables -C FORWARD -i "$UPSTREAM" -o wlan+ -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT 2>/dev/null \
  || iptables -A FORWARD -i "$UPSTREAM" -o wlan+ -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT

# --- start everything --------------------------------------------------------
log "Starting services..."
systemctl daemon-reload
systemctl enable dnsmasq.service hostapd.service hotspot-setup.service
systemctl restart dnsmasq.service hostapd.service hotspot-setup.service

# --- report -------------------------------------------------------------------
echo
log "Hotspot status:"
IFACE=$(cat /run/hotspot-iface 2>/dev/null || echo '?')
printf '    interface : %s (%s)\n' "$IFACE" "$(cat /sys/class/net/$IFACE/address 2>/dev/null || echo 'not found')"
printf '    mode      : %s\n' "$(iw dev "$IFACE" info 2>/dev/null | awk '/type/{print $2}' || echo '?')"
printf '    IP        : %s\n' "$(ip -4 -o addr show dev "$IFACE" 2>/dev/null | awk '{print $4}' || echo 'pending')"
for u in hotspot-setup hostapd dnsmasq iptables; do
  printf '    %-9s : %s\n' "$u" "$(systemctl is-active "$u" 2>/dev/null)"
done
echo
log "Connect clients to SSID '$SSID' with password '$PASSWORD' (shares $UPSTREAM)."
